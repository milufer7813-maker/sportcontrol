  if (!exercise) return res.status(404).json({ error: "Ejercicio no encontrado." });
  const { routineId, name, detail } = req.body || {};
  const day = req.body?.day === undefined ? 1 : Number(req.body.day);
  if (!routines.some(item => item.id === Number(routineId)) || !Number.isInteger(day) || day < 1 || day > 30 || !String(name || "").trim() || !String(detail || "").trim()) {
    return res.status(400).json({ error: "Envía una rutina, un día válido, el nombre y el detalle del ejercicio." });
  }
  Object.assign(exercise, { routineId: Number(routineId), day, name: String(name).trim(), detail: String(detail).trim() });
